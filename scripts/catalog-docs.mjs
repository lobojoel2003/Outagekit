// Writes docs/catalog.md from the JSON catalog so it can be read on GitHub.
// Usage: pnpm catalog:docs  (CI fails if the file is out of date)
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { root } from './versions.mjs';

const read = (file) =>
  JSON.parse(readFileSync(join(root, 'packages/runtime/src/catalog', file), 'utf8'));
const { devices, updated } = read('devices.json');
const { powerSources } = read('power-sources.json');

const CATEGORY = {
  'oxygen-concentrator': 'Oxygen concentrators',
  'portable-oxygen-concentrator': 'Portable oxygen concentrators',
  cpap: 'CPAP',
  bilevel: 'Bilevel (BiPAP)',
  ventilator: 'Home ventilators',
  bed: 'Powered beds',
  mattress: 'Pressure mattresses',
  suction: 'Suction',
  nebulizer: 'Nebulizers',
  'feeding-pump': 'Feeding pumps',
  'infusion-pump': 'Infusion pumps',
  dialysis: 'Dialysis',
  mobility: 'Mobility',
  monitor: 'Monitors',
  refrigeration: 'Refrigeration',
  communication: 'Phones and internet',
  lighting: 'Lighting',
  climate: 'Heating and cooling',
  other: 'Other',
};

const cell = (text) =>
  String(text ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ');
const name = (item) => (item.manufacturer ? `${item.manufacturer} ${item.name}` : item.name);
const sources = (item) =>
  item.sources.map((s) => (s.url ? `[${cell(s.title)}](${s.url})` : cell(s.title))).join('<br>');

const out = [];
out.push('# Device and power source catalog');
out.push('');
out.push(
  `<!-- Generated by scripts/catalog-docs.mjs from packages/runtime/src/catalog. Do not edit by hand. -->`,
);
out.push('');
out.push(
  `The open catalog behind Outagekit: **${devices.length} devices** and **${powerSources.length} power sources**, last reviewed ${updated}. ` +
    'It is MIT licensed and ships as JSON in [`@outagekit/runtime`](../packages/runtime). ' +
    'Watts are average draw at the wall for each setting. ✅ means the figure was checked against a manufacturer document; ' +
    'other figures are typical values and the app tells people to check their own label.',
);
out.push('');
out.push(
  'Found a better figure? [Open a catalog correction](https://github.com/lobojoel2003/Outagekit/issues/new?template=catalog.yml).',
);
out.push('');
out.push('## Devices');
for (const [category, label] of Object.entries(CATEGORY)) {
  const items = devices.filter((d) => d.category === category);
  if (!items.length) continue;
  out.push('');
  out.push(`### ${label}`);
  out.push('');
  out.push('| Device | Settings (watts) | Runs | Priority | Source |');
  out.push('| --- | --- | --- | --- | --- |');
  for (const d of items) {
    const settings = d.settings.map((s) => `${cell(s.label)}: ${s.watts} W`).join('<br>');
    const runs =
      d.dutyCycle >= 1 ? 'continuously' : `${Math.round(d.dutyCycle * 100)}% of the time`;
    const battery = d.internalBattery ? `<br>Own battery: ~${d.internalBattery.hours} h` : '';
    out.push(
      `| ${d.verified ? '✅ ' : ''}${cell(name(d))} | ${settings} | ${runs}${battery} | ${d.priority} | ${sources(d)} |`,
    );
  }
}
out.push('');
out.push('## Power sources');
out.push('');
out.push('| Power source | Capacity | Chemistry | AC output | Cycles to 80% | Source |');
out.push('| --- | --- | --- | --- | --- | --- |');
for (const p of powerSources) {
  out.push(
    `| ${p.verified ? '✅ ' : ''}${cell(name(p))} | ${p.capacityWh.toLocaleString('en-US')} Wh | ${p.chemistry} | ${
      p.acOutputWatts ? `${p.acOutputWatts.toLocaleString('en-US')} W` : '—'
    } | ${p.cycleLifeTo80 ?? '—'} | ${sources(p)} |`,
  );
}
out.push('');

const file = join(root, 'docs/catalog.md');
const text = out.join('\n');
if (process.argv.includes('--check')) {
  const current = (() => {
    try {
      return readFileSync(file, 'utf8');
    } catch {
      return '';
    }
  })();
  if (current !== text) {
    console.error('docs/catalog.md is out of date. Run: pnpm catalog:docs');
    process.exit(1);
  }
  console.log('docs/catalog.md is up to date.');
} else {
  writeFileSync(file, text);
  console.log(
    `Wrote docs/catalog.md (${devices.length} devices, ${powerSources.length} power sources).`,
  );
}
